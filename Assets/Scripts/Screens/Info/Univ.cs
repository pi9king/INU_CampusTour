    public void DepartClick()
    {
        temptext = EventSystem.current.currentSelectedGameObject.name;
        string departmentName = GameObject.Find(temptext).GetComponentInChildren<Text>().text;
        if (string.IsNullOrEmpty(departmentName))
        {
            return;
        }

        int pageCount;
        if (!CurriculumPageCounts.TryGetValue(departmentName, out pageCount))
        {
            pageCount = 1;
        }
        ScreenNavigator.Instance.Push(ScreenRegistry.DeptInfoFor(pageCount), new NameArgs(departmentName));
    }

